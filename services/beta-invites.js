/**
 * Beta invites: the owner approves an applicant from the landing site's beta
 * sign-up, the applicant gets a one-time code by email, and only a sign-up that
 * carries a valid code (for the same email) can make an account.
 *
 * STAGED (2026-10-24, curriculum-build/BETA-LAUNCH-KIT.md section 4). Nothing in
 * the app loads this until middleware/beta-gate.js is mounted (see
 * curriculum-build/staged/beta-launch/server.js.patch). The CLI is
 * scripts/beta-invites.js.
 *
 * Storage: one small JSON file, BETA_INVITES_FILE, default `beta-invites.json`
 * beside the data file (so a test on its own DB_FILE keeps its own invites). It
 * is separate from db.json on purpose: invites exist before any account does,
 * and the landing site's applicant list (site/data/beta.jsonl) is never written
 * by the app.
 *
 * A code is 10 characters of Crockford base32 (no I, L, O, U), shown as
 * XXXXX-XXXXX: 50 bits, generated by crypto.randomBytes. Only its SHA-256 is
 * stored, so the file cannot be used to sign up; the code exists in the email
 * and nowhere else. Lost code: revoke and approve again.
 *
 * NOT built here: the tester consent gate (tester terms, a parent's acceptance
 * for minors). The owner's decision is recorded in memory; the auto-mode safety
 * checker blocked building it on 2026-10-23 and it stays blocked in this
 * session. `redeem()` records `terms_accepted: null` so that gate has a field to
 * fill when it is built elsewhere.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ALPHABET = '0123456789ABCDEFGHJKMNPQRSTVWXYZ'; // Crockford base32
const DEFAULT_DAYS = 30;

function storeFile() {
  if (process.env.BETA_INVITES_FILE) return path.resolve(process.env.BETA_INVITES_FILE);
  const dir = process.env.DB_FILE ? path.dirname(path.resolve(process.env.DB_FILE)) : path.join(__dirname, '..', 'data');
  return path.join(dir, 'beta-invites.json');
}

function load() {
  try {
    const parsed = JSON.parse(fs.readFileSync(storeFile(), 'utf8'));
    if (parsed && Array.isArray(parsed.invites)) return parsed;
  } catch (err) {
    if (err.code !== 'ENOENT') throw new Error(`beta invites file is unreadable: ${err.message}`);
  }
  return { version: 1, invites: [] };
}

function save(store) {
  const file = storeFile();
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(`${file}.tmp`, JSON.stringify(store, null, 2), { mode: 0o600 });
  fs.renameSync(`${file}.tmp`, file);
}

const normEmail = (e) => String(e || '').trim().toLowerCase();

/** Upper-case, drop spaces and dashes, and read the look-alikes as Crockford does. */
function normCode(code) {
  return String(code || '').toUpperCase().replace(/[\s-]/g, '').replace(/[IL]/g, '1').replace(/O/g, '0');
}

const hashCode = (code) => crypto.createHash('sha256').update(`savant-beta:${normCode(code)}`).digest('hex');

function newCode() {
  const bytes = crypto.randomBytes(10);
  let out = '';
  for (let i = 0; i < 10; i++) out += ALPHABET[bytes[i] & 31];
  return `${out.slice(0, 5)}-${out.slice(5)}`;
}

function publicInvite(inv) {
  const { code_hash: _omit, ...rest } = inv;
  return rest;
}

/**
 * Approve one email. Returns { code, invite }. An address with a live invite
 * gets a fresh code and the old one stops working (re-sending, after a lost email).
 */
function approve(email, { name = null, role = null, source = null, days = DEFAULT_DAYS, now = new Date(), by = null } = {}) {
  const addr = normEmail(email);
  if (!/^[^\s@<>]+@[^\s@<>]+\.[^\s@<>]+$/.test(addr)) throw new Error(`not an email address: ${email}`);
  const store = load();
  for (const inv of store.invites) {
    if (inv.email === addr && inv.status === 'invited') { inv.status = 'replaced'; inv.replaced_at = now.toISOString(); }
  }
  const code = newCode();
  const invite = {
    id: crypto.randomBytes(6).toString('hex'),
    email: addr,
    name: name ? String(name).slice(0, 80) : null,
    role: role || null,
    source: source || null,
    code_hash: hashCode(code),
    status: 'invited',
    approved_by: by,
    invited_at: now.toISOString(),
    expires_at: new Date(now.getTime() + days * 86400000).toISOString(),
    emailed_at: null,
    redeemed_at: null,
    user_id: null,
    terms_accepted: null,
  };
  store.invites.push(invite);
  save(store);
  return { code, invite: publicInvite(invite) };
}

/**
 * Is this code good for a sign-up by these addresses? `emails` is every address
 * the sign-up names: the adult's own, or a child's parent email. With
 * BETA_BIND_EMAIL=0 a code works for any address (codes may then be passed on).
 */
function check(code, emails, { now = new Date() } = {}) {
  if (!code) return { ok: false, reason: 'missing' };
  const hash = hashCode(code);
  const inv = load().invites.find((i) => i.code_hash === hash);
  if (!inv) return { ok: false, reason: 'unknown' };
  if (inv.status === 'redeemed') return { ok: false, reason: 'used' };
  if (inv.status !== 'invited') return { ok: false, reason: inv.status };
  if (new Date(inv.expires_at) < now) return { ok: false, reason: 'expired' };
  const bind = process.env.BETA_BIND_EMAIL !== '0';
  const given = (Array.isArray(emails) ? emails : [emails]).map(normEmail).filter(Boolean);
  if (bind && !given.includes(inv.email)) return { ok: false, reason: 'other_email' };
  return { ok: true, invite: publicInvite(inv) };
}

/** Mark the code used by this account. Returns the invite, or null if it was no longer valid. */
function redeem(code, userId, { now = new Date() } = {}) {
  const store = load();
  const hash = hashCode(code);
  const inv = store.invites.find((i) => i.code_hash === hash && i.status === 'invited');
  if (!inv) return null;
  inv.status = 'redeemed';
  inv.redeemed_at = now.toISOString();
  inv.user_id = userId;
  save(store);
  return publicInvite(inv);
}

function markEmailed(id, { now = new Date() } = {}) {
  const store = load();
  const inv = store.invites.find((i) => i.id === id);
  if (!inv) return null;
  inv.emailed_at = now.toISOString();
  save(store);
  return publicInvite(inv);
}

/** Stop every live invite for an address. Returns how many. */
function revoke(email, { now = new Date() } = {}) {
  const store = load();
  let n = 0;
  for (const inv of store.invites) {
    if (inv.email === normEmail(email) && inv.status === 'invited') { inv.status = 'revoked'; inv.revoked_at = now.toISOString(); n++; }
  }
  if (n) save(store);
  return n;
}

/** Remove every invite row for an address (a tester asks to be forgotten). */
function forget(email) {
  const store = load();
  const before = store.invites.length;
  store.invites = store.invites.filter((i) => i.email !== normEmail(email));
  if (store.invites.length !== before) save(store);
  return before - store.invites.length;
}

function list() {
  return load().invites.map(publicInvite);
}

/** Was this account created through an invite? */
function isTester(userId) {
  return load().invites.some((i) => i.status === 'redeemed' && i.user_id === userId);
}

/**
 * Read the landing site's beta applications (site/data/beta.jsonl, one JSON
 * object per line, written by site/server.js). Read-only. Each row comes back
 * with its invite state from this store.
 */
function applicants(jsonlFile) {
  let text = '';
  try { text = fs.readFileSync(jsonlFile, 'utf8'); } catch (err) {
    if (err.code === 'ENOENT') return [];
    throw err;
  }
  const invites = load().invites;
  return text.split('\n').filter(Boolean).map((line) => { try { return JSON.parse(line); } catch { return null; } })
    .filter((r) => r && r.email)
    .map((r) => {
      const mine = invites.filter((i) => i.email === normEmail(r.email));
      const latest = mine[mine.length - 1];
      return { id: r.id, at: r.at, email: normEmail(r.email), name: r.name || null, role: r.role || null, invite: latest ? latest.status : 'none' };
    });
}

/** The invitation email. `origin` is the app's public origin (APP_ORIGIN). */
function inviteEmail({ to, name, code, origin, days = DEFAULT_DAYS }) {
  const base = String(origin || '').replace(/\/$/, '');
  const link = `${base}/join?invite=${encodeURIComponent(code)}`;
  return {
    to,
    subject: 'Your Savant beta invite',
    tag: 'beta-invite',
    text: [
      `Hi${name ? ` ${name}` : ''},`,
      '',
      'You are in: thank you for applying to test Savant. Beta testers use it completely free.',
      '',
      `Open this link to make your account: ${link}`,
      `Or go to ${base}/register and enter this code: ${code}`,
      '',
      `The code works once, for this email address, for ${days} days.`,
      'If you are signing up for a child, use this email as the parent email on the sign-up form.',
      '',
      'If you did not apply, ignore this email and nothing will happen.',
    ].join('\n'),
  };
}

module.exports = {
  approve, check, redeem, revoke, forget, list, isTester, applicants, markEmailed, inviteEmail,
  normCode, hashCode, newCode, storeFile,
};
