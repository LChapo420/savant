/**
 * Writes assets/grade-levels.js: how many levels each grade has in the app's base
 * curriculum (config/curriculum.js, a grade's pathLength), per subject, in path
 * order. The page's grade strips draw one bar per grade at that height.
 *
 *   node site/tools/build-grade-levels.js      (run again when the curriculum changes)
 */
const fs = require('fs');
const path = require('path');

const curriculum = require(path.join(__dirname, '..', '..', 'config', 'curriculum'));
const out = {};
for (const track of curriculum.TRACKS) out[track.id] = track.grades.map((g) => g.pathLength);

const file = path.join(__dirname, '..', 'assets', 'grade-levels.js');
fs.writeFileSync(file, `/* Generated by site/tools/build-grade-levels.js from config/curriculum.js: levels per grade, in path order. */\nwindow.SAVANT_GRADE_LEVELS = ${JSON.stringify(out)};\n`);
console.log(`wrote ${path.relative(process.cwd(), file)}: ${Object.entries(out).map(([k, v]) => `${k} ${v.length}`).join(', ')}`);
