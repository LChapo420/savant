/** One compact content-only AI call, reused by every preview. No learner DB writes. */
require('dotenv').config({ path: require('path').join(__dirname, '..', '..', '.env') });
process.env.DB_READONLY = '1';
const fs = require('fs');
const lab = require('../services/game-lab');
const providers = require('../services/providers');
const schema = {
  type: 'object', additionalProperties: false, required: ['questions'],
  properties: { questions: { type: 'array', minItems: 50, maxItems: 50, items: {
    type: 'object', additionalProperties: false, required: ['prompt', 'choices', 'answerIndex', 'explanation'],
    properties: { prompt: { type: 'string' }, choices: { type: 'array', minItems: 4, maxItems: 4, items: { type: 'string' } }, answerIndex: { type: 'integer', minimum: 0, maximum: 3 }, explanation: { type: 'string' } },
  } } },
};
(async () => {
  if (fs.existsSync(lab.CACHE) && !process.argv.includes('--force')) { console.log('Using cached game lab questions.'); return; }
  const provider = process.env.LAB_PROVIDER ? providers.ALL[process.env.LAB_PROVIDER] : providers.current('blocks');
  if (!provider) throw new Error('No provider configured. No question content generated.');
  const reply = await provider.structured({ role: 'blocks', system: 'You write accurate educational rhetoric questions. Output only the requested structure.', user: lab.PROMPT, schema, schemaName: 'game_lab_questions', maxTokens: 14000, lane: 'background' });
  const data = reply && (reply.data || reply);
  if (!data || !Array.isArray(data.questions) || data.questions.length !== 50 || data.questions.some((q) => !q.prompt || !q.explanation || !Array.isArray(q.choices) || q.choices.length !== 4 || new Set(q.choices).size !== 4 || !Number.isInteger(q.answerIndex) || q.answerIndex < 0 || q.answerIndex > 3)) throw new Error('Provider output failed validation; cache not written.');
  fs.writeFileSync(lab.CACHE, JSON.stringify({ source: `Shared topic questions generated by ${provider.name} / ${provider.modelFor('blocks')}; cached once, reused across 40 engines.`, generatedAt: new Date().toISOString(), questions: data.questions }, null, 2));
  console.log('Saved 50 shared ethos/logos/pathos questions.');
})().catch((err) => { console.error(err.message); process.exitCode = 1; });