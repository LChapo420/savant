// Generate public/spanish/css/tokens.css from config/spanish/tokens.json.
//
// The token file holds roles, not colours: a rebrand changes values there and
// re-runs this script; no component CSS changes. Light is the base, dark comes
// from the system setting, and data-theme on <html> overrides both (the
// Dark mode setting: system / on / off).
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const SRC = path.join(ROOT, 'config', 'spanish', 'tokens.json');
const OUT = path.join(ROOT, 'public', 'spanish', 'css', 'tokens.css');

const t = JSON.parse(fs.readFileSync(SRC, 'utf8'));

const colourVars = (set) => Object.entries(set)
  .map(([k, v]) => `  --es-${k}: ${v};`).join('\n');

const lines = [];
lines.push('/* Generated by scripts/spanish/build-tokens.js from config/spanish/tokens.json. Do not edit. */');
lines.push(':root {');
lines.push(colourVars(t.color.light));
lines.push(`  --es-font: ${t.font.sans};`);
lines.push(`  --es-mono: ${t.font.mono};`);
for (const [k, v] of Object.entries(t.type)) {
  lines.push(`  --es-text-${k}: ${v.size}px;`);
  lines.push(`  --es-line-${k}: ${v.line}px;`);
  lines.push(`  --es-weight-${k}: ${v.weight};`);
}
t.space.forEach((v, i) => lines.push(`  --es-space-${i}: ${v}px;`));
for (const [k, v] of Object.entries(t.radius)) lines.push(`  --es-radius-${k}: ${v}px;`);
for (const [k, v] of Object.entries(t.border)) lines.push(`  --es-border-${k}: ${v}px;`);
for (const [k, v] of Object.entries(t.shadow)) lines.push(`  --es-shadow-${k}: ${v};`);
for (const [k, v] of Object.entries(t.motion)) lines.push(`  --es-motion-${k}: ${v};`);
const L = t.layout;
for (const k of ['rail-collapsed', 'rail-expanded', 'right-rail', 'path-max', 'lesson-max', 'header-mobile', 'tabbar-mobile', 'tap-min']) {
  lines.push(`  --es-${k}: ${L[k]}px;`);
}
lines.push(`  --es-node-w: ${L.node.w}px;`);
lines.push(`  --es-node-h: ${L.node.h}px;`);
for (const [k, v] of Object.entries(L['button-h'])) lines.push(`  --es-button-${k}: ${v}px;`);
lines.push('  color-scheme: light;');
lines.push('}');
lines.push('');
lines.push('@media (prefers-color-scheme: dark) {');
lines.push('  :root:not([data-theme="light"]) {');
lines.push(colourVars(t.color.dark).replace(/^ {2}/gm, '    '));
lines.push('    color-scheme: dark;');
lines.push('  }');
lines.push('}');
lines.push(':root[data-theme="dark"] {');
lines.push(colourVars(t.color.dark));
lines.push('  color-scheme: dark;');
lines.push('}');
lines.push('');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`tokens.css written: ${Object.keys(t.color.light).length} light / ${Object.keys(t.color.dark).length} dark colour roles`);
