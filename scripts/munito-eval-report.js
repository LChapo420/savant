#!/usr/bin/env node
/**
 * Aggregates the Munito benchmark results (curriculum-build/munito-eval/munito-eval.json, baseline.json) and the live
 * Munito ledger (data/munito-ledger.json: calls, failed, refused, by_model, by_task, outcomes) into markdown tables on stdout.
 * Read only. MUNITO_LEDGER_FILE overrides the ledger path (default: the live ledger in the owner's folder).
 *
 *   node scripts/munito-eval-report.js > tables.md
 */
const fs = require('fs');
const path = require('path');
const DIR = path.join(__dirname, '..', 'curriculum-build', 'munito-eval');
const LEDGER = process.env.MUNITO_LEDGER_FILE || 'C:/coding/claudecommittdIq/folderThing/iq-max-repo-2-claude-adoring-mayer-woc9sq/data/munito-ledger.json';
const read = (f) => { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch { return null; } };
const n = (v, d = 0) => (v === null || v === undefined ? 'n/a' : Number(v).toFixed(d));
const sec = (ms) => (ms === null || ms === undefined ? 'n/a' : (ms / 1000).toFixed(1));
const short = (m) => m.replace(/^[^/]+\//, '');

function benchTables(title, rows) {
  if (!rows || !rows.length) return '';
  const o = [`### ${title}`, ''];
  o.push('| Model | Short p50 / p95 (s) | 3k-token p50 / p95 (s) | Out tok/s (3k) | Error rate (429s) | Timeouts | Empty | JSON valid /10 | MCQ right / answered (of 40) | Cost per 1,000 MCQ tasks |');
  o.push('|---|---|---|---|---|---|---|---|---|---|');
  for (const r of rows) {
    if (!r.short) { o.push(`| ${short(r.model)} | skipped: ${r.skipped || 'no data'} | | | | | | | | |`); continue; }
    o.push(`| ${short(r.model)}${r.skipped ? ' (' + r.skipped + ')' : ''} | ${sec(r.short.p50_ms)} / ${sec(r.short.p95_ms)} | ${sec(r.long.p50_ms)} / ${sec(r.long.p95_ms)} | ${n(r.long.out_tok_per_s, 1)} | ${n(100 * r.reliability.error_rate, 0)}% (${r.reliability.rate_limited}/${r.reliability.total}) | ${r.reliability.timeout} | ${r.reliability.empty_or_unusable} | ${r.structured.valid} | ${r.mcq.right} / ${r.mcq.answered}${r.mcq.answered ? ` (${n(100 * r.mcq.right / r.mcq.answered, 0)}% of answered)` : ""} | $${n(r.cost.per_1000_mcq_tasks_usd, 3)} |`);
  }
  o.push('', 'MCQ accuracy by bank (right of 10):', '', '| Model | spanish | english | math | reading | answered | avg output tokens |', '|---|---|---|---|---|---|---|');
  for (const r of rows.filter((x) => x.mcq)) o.push(`| ${short(r.model)} | ${['spanish', 'english', 'math', 'reading'].map((b) => r.mcq.by_bank[b].right).join(' | ')} | ${r.mcq.answered} | ${n(r.mcq.avg_out_tokens)} |`);
  o.push('');
  return o.join('\n');
}

function main() {
  const main = read(path.join(DIR, 'munito-eval.json'));
  const base = read(path.join(DIR, 'baseline.json'));
  const v4 = read(path.join(DIR, 'munito-eval-v4flash-conc1.json'));
  const out = ['# Munito benchmark and ledger tables (generated by scripts/munito-eval-report.js)', ''];
  if (main) {
    out.push(`Benchmark run ${main.generated_at}. ${main.label}. Own counted spend $${n(main.own_counted_usd, 4)}; ledger moved $${n(main.ledger_delta_usd, 4)} over the run (includes any other process using the same ledger).`, '');
    out.push('Item sources: ' + main.item_sources.map((s) => `${s.bank} (${s.file}, ${s.drawn} of ${s.of})`).join('; ') + `; seed ${main.seed}.`, '');
    out.push(benchTables('Munito models', main.models));
  }
  if (v4) out.push(benchTables('deepseek-v4-flash re-run, one request at a time (--conc 1)', v4.models));
  if (base) out.push(benchTables('Free baseline (NVIDIA free tier, same tasks; context only)', base.baseline));
  const l = read(LEDGER);
  if (l) {
    out.push('### Live Munito ledger (all uses of the key, not only the benchmark)', '');
    out.push(`Spent $${n(l.settled_usd, 2)} of $${l.cap_usd}; ${l.calls} calls, ${l.failed_calls} failed, ${l.refused_calls} refused by the local cap.`, '');
    out.push('| Model | Calls | Billed USD |', '|---|---|---|');
    for (const [m, v] of Object.entries(l.by_model || {})) out.push(`| ${m} | ${v.calls} | ${n(v.usd, 3)} |`);
    out.push('', '| Task | Calls | Billed USD |', '|---|---|---|');
    for (const [t, v] of Object.entries(l.by_task || {})) out.push(`| ${t} | ${v.calls} | ${n(v.usd, 3)} |`);
    const oc = {}; const per = {};
    for (const e of l.log || []) {
      oc[e.outcome] = (oc[e.outcome] || 0) + 1;
      const p = (per[e.model] = per[e.model] || {}); p[e.outcome] = (p[e.outcome] || 0) + 1;
    }
    out.push('', `Outcomes in the retained log (last ${(l.log || []).length} calls): ${Object.entries(oc).map(([k, v]) => `${k} ${v}`).join(', ')}.`, '');
    out.push('| Model | ' + Object.keys(oc).join(' | ') + ' |', '|---|' + Object.keys(oc).map(() => '---').join('|') + '|');
    for (const [m, p] of Object.entries(per)) out.push(`| ${m} | ${Object.keys(oc).map((k) => p[k] || 0).join(' | ')} |`);
    out.push('', '"not_billed" means the API answered with an error (not billed); "unknown" means a timeout or network failure, counted at the reserved worst case.');
  }
  console.log(out.join('\n'));
}
main();
