/**
 * The syllabus: what each level actually teaches, in the order a class teaches it.
 *
 * A skill is not a topic. `parts_of_speech` owns a band of levels, and every one
 * of those levels used to serve a lesson titled with the skill's name and a level
 * number — the same lesson, five times, teaching nothing new on the second. So a
 * skill is an ordered list of topics, and a level takes the one its position in
 * the grade calls for.
 *
 * The sequences below are real curricula rather than invention: Common Core for
 * the English and maths grades, Big Ideas Math for the algebra sequence, ACTFL-
 * aligned district Spanish scope-and-sequences with AP Central's six thematic
 * units for the advanced Spanish, and College Board / CogAT content families for
 * the IQ tracks. The grounding is in the commit that added this file and in
 * README.md, which cites the standards each list is drawn from.
 *
 * Three properties the file has to keep, and the self-test holds all three for
 * every grade:
 *
 *   **Prerequisites first.** Nothing in a list depends on something after it.
 *   Nouns and verbs come before agreeing them, agreeing before punctuating,
 *   punctuating before joining them into longer sentences, and only then choosing
 *   between words that are all individually correct.
 *
 *   **One lesson per topic.** `content/topics.js` spreads the grade's lesson
 *   levels across this list, so the first lesson is the first topic and the last
 *   is the last. Where a list is shorter than the number of lessons, the extra
 *   lessons go deeper on the last topics rather than inventing a heading over
 *   material that was not written.
 *
 *   **A topic is a family or a shape, not a label.** `topics.js` matches each
 *   entry to the family that can actually be asked about it, so a lesson on
 *   "Nouns and the words that name them" is followed by a question about nouns
 *   and not about a dangling participle.
 */

